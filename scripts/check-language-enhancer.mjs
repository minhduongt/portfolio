import assert from 'node:assert/strict';
import { enhancementPayload, readEnhancement } from '../src/site/tools/languageEnhancerLogic.js';
import { toolDefinition } from '../src/site/api.js';
const guestRecord = toolDefinition({ slug: 'language-enhancer', name: 'Language Enhancer', visibility: 'limited', locked: true });
assert.equal(guestRecord.remote, true, 'Redacted guest metadata still shows the remote-input privacy notice');
assert.equal(guestRecord.id, null, 'Redacted metadata does not resolve executable components');
const sentence = { mode: 'sentence', text: '  I very like English.  ', language: 'en', explanationLanguage: 'vi', tone: 'natural', context: '' };
const request = enhancementPayload(sentence);
assert.equal(request.text, 'I very like English.');
assert.throws(() => enhancementPayload({ ...sentence, text: ' ' }));
assert.throws(() => enhancementPayload({ ...sentence, text: 'a'.repeat(2001) }));
assert.throws(() => enhancementPayload({ ...sentence, context: 'a'.repeat(501) }));
const keyword = enhancementPayload({ ...sentence, mode: 'keyword', text: 'happy' });
assert(!Object.hasOwn(keyword, 'tone'));
assert.throws(() => enhancementPayload({ ...sentence, mode: 'keyword', text: 'a'.repeat(101) }));
const alternatives = Array.from({ length: 3 }, () => ({ text: 'I really like English.', explanation: 'Use really.', context: 'Conversation.' }));
assert.deepEqual(readEnhancement({ ...request, result: { alternatives } }, request).alternatives, alternatives);
assert.throws(() => readEnhancement({ ...request, result: { alternatives: alternatives.slice(0, 2) } }, request));
const vocabulary = { meaning: 'Feeling pleased.', partOfSpeech: 'Adjective', synonyms: [], antonyms: [], examples: [{ text: 'I am happy.', explanation: 'A feeling.', context: 'Daily life.' }], notes: 'Meaning depends on context.' };
assert.deepEqual(readEnhancement({ ...keyword, result: vocabulary }, keyword), vocabulary);
assert.throws(() => readEnhancement({ ...keyword, language: 'vi', result: vocabulary }, keyword));
assert.throws(() => readEnhancement({ ...keyword, result: { ...vocabulary, notes: '' } }, keyword));
assert.throws(() => readEnhancement({ ...keyword, result: { ...vocabulary, synonyms: [{ word: 'glad' }] } }, keyword));
console.log('Language enhancer: bounded mode payloads and complete structured response validation passed.');
